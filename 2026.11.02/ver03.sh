
#!/bin/bash
# 使用 Bash Shell 執行智慧成績審核系統


# ============================================================
# 1. 讀取學生資料
# ============================================================

read -r -p "請輸入學生學號: " id
# -r：避免反斜線被解讀成特殊字元
# -p：顯示輸入提示
# 將輸入的學號存入 id

if [ -z "$id" ]; then
    # -z：檢查字串是否為空

    echo "錯誤：學號不得為空字串！"
    exit 1
fi

read -r -p "請輸入數學成績: " score
# 讀取數學成績

read -r -p "請輸入程式檔案名稱: " filename
# 讀取學生繳交的程式檔名


# ============================================================
# 2. 使用 CASE 判斷學生科系
# ============================================================

first_char="${id:0:1}"
# ${id:0:1}：取得學號第一個字元
# 0 代表從第一個字元的位置開始
# 1 代表只取一個字元

case "$first_char" in

    E)
        dept="ELECTRICAL ENGINEERING"
        ;;

    C)
        dept="COMPUTER SCIENCE"
        ;;

    M)
        dept="MECHANICAL ENGINEERING"
        ;;

    *)
        echo "錯誤：非法的科系代號！"
        exit 1
        ;;

esac


# ============================================================
# 3. 檢查成績是否合法
# ============================================================

case "$score" in

    ''|*[!0-9]*)
        # ''：空字串
        # *[!0-9]*：包含非數字字元
        # 例如 abc、90a、85.5、-10

        echo "錯誤：成績必須是 0~100 的整數！"
        exit 1
        ;;

esac

# 去除成績前面的 0，避免數字比較時出現格式問題
score_num="${score#"${score%%[!0]*}"}"

# 如果輸入的全部都是 0，將結果設定為 0
if [ -z "$score_num" ]; then
    score_num=0
fi

case "$score_num" in
    ????*)
        # ????*：至少四個字元
        # 成績最多只需要三位數，因此四位以上不合法

        echo "錯誤：成績不得超過 100！"
        exit 1
        ;;
esac

# 檢查成績是否超過 100
if [ "$score_num" -gt 100 ]; then
    echo "錯誤：成績必須介於 0 到 100 之間！"
    exit 1
fi


# ============================================================
# 4. 使用 CASE 判斷成績等級及評語
# ============================================================

case "$score_num" in

    100|9[0-9])
        grade="A+"
        comment="EXCELLENT"
        ;;

    8[0-9])
        grade="A"
        comment="VERY GOOD"
        ;;

    7[0-9])
        grade="B"
        comment="GOOD"
        ;;

    6[0-9])
        grade="C"
        comment="PASS"
        ;;

    *)
        grade="F"
        comment="FAIL"
        ;;

esac


# ============================================================
# 5. 檢查學生繳交的程式檔名
# ============================================================

expected_name="${id}.SH"
# 將學號與 .SH 組合成正確檔名

if [ "$filename" != "$expected_name" ]; then
    # !=：比較兩個字串是否不相等

    echo "錯誤：檔名必須為 $expected_name！"
    exit 1
fi


# ============================================================
# 6. 檢查程式檔案的四種屬性
# ============================================================

if [ ! -e "$filename" ]; then
    # -e：檢查檔案是否存在

    echo "錯誤：檔案不存在！"
    exit 1

elif [ ! -f "$filename" ]; then
    # -f：檢查是否為普通檔案

    echo "錯誤：不是普通檔案！"
    exit 1

elif [ ! -r "$filename" ]; then
    # -r：檢查是否具有讀取權限

    echo "錯誤：檔案不可讀取！"
    exit 1

elif [ ! -x "$filename" ]; then
    # -x：檢查是否具有執行權限

    echo "錯誤：檔案不可執行！"
    exit 1

fi


# ============================================================
# 7. 決定成績資料的輸出檔案
# ============================================================

out_file="GRADE"
# 預設將資料寫入 GRADE

if [ -e "$out_file" ]; then
    # 如果 GRADE 已經存在，就要求使用者另外輸入檔名

    read -r -p "GRADE 已存在，請輸入新的輸出檔名: " out_file

    if [ -z "$out_file" ] || [ "$out_file" = "GRADE" ] || [ -d "$out_file" ] || [ "$out_file" = "$filename" ]; then

        # -z：新檔名不得為空
        # = GRADE：不得再次使用 GRADE
        # -d：不得是已存在的目錄
        # = filename：不得使用學生繳交的程式檔當作輸出檔

        echo "錯誤：新的輸出檔名不合法！"
        exit 1
    fi

fi

# 再次確認輸出位置是否為合法檔案
if [ -d "$out_file" ]; then
    echo "錯誤：輸出位置是目錄！"
    exit 1

elif [ -e "$out_file" ] && [ ! -f "$out_file" ]; then
    echo "錯誤：輸出位置不是普通檔案！"
    exit 1

elif [ -e "$out_file" ] && [ ! -r "$out_file" ]; then
    echo "錯誤：輸出檔案不可讀取！"
    exit 1

elif [ -e "$out_file" ] && [ ! -w "$out_file" ]; then
    echo "錯誤：輸出檔案不可寫入！"
    exit 1

fi


# ============================================================
# 8. 新增功能一：學生成績歷史紀錄與重複審核提醒
# ============================================================

search_id="學生學號：$id"
# 建立要搜尋的完整學號文字
# 例如：學生學號：E1234567

if [ -e "$out_file" ]; then
    # 只有輸出檔案已存在時才需要搜尋歷史紀錄

    if grep -F -x -q "$search_id" "$out_file"; then

        # grep：搜尋檔案內容
        # -F：使用一般文字比對，不將內容當正規表示式
        # -x：要求整行完全符合
        # -q：只回傳搜尋結果，不直接顯示搜尋內容

        echo ""
        echo "========================================"
        echo "警告：發現此學生曾經有審核紀錄！"
        echo "========================================"

        echo "以下為過去的審核資料："

        grep -F -x -A 8 "$search_id" "$out_file"
        # -A 8：除了符合的那一行，也顯示後面 8 行
        # 讓使用者可以看到先前的成績與等級

        echo "========================================"

        echo "提醒：如果繼續，將會新增一筆審核紀錄。"

    else

        echo "尚未發現此學號的歷史審核紀錄。"

    fi

else

    echo "目前尚無成績歷史紀錄。"

fi


# ============================================================
# 9. 新增功能二：自動產生成績統計資訊
# ============================================================

if [ "$score_num" -ge 60 ]; then

    # -ge：大於或等於
    # 60 分以上代表及格

    pass_status="及格"

else

    pass_status="不及格"

fi

# 計算距離下一個成績等級所需要的分數

case "$grade" in

    F)
        next_grade="C"
        next_score=60
        ;;

    C)
        next_grade="B"
        next_score=70
        ;;

    B)
        next_grade="A"
        next_score=80
        ;;

    A)
        next_grade="A+"
        next_score=90
        ;;

    A+)
        next_grade="最高等級"
        ;;

esac

if [ "$grade" = "A+" ]; then

    progress="已達最高等級！"

else

    points_needed=$((next_score - score_num))
    # $(( ))：Bash 整數算術運算
    # 計算下一個等級的門檻減去目前成績

    progress="距離下一級 ${next_grade} 還差 ${points_needed} 分"

fi

percentage="${score_num}%"
# 成績百分比，例如 92 分就是 92%


# ============================================================
# 10. 取得系統時間
# ============================================================

current_time=$(date "+%Y-%m-%d %H:%M:%S")
# date：取得目前日期與時間
# $()：命令替換，將執行結果存入變數


# ============================================================
# 11. 整理完整成績報告
# ============================================================

result_str="
========================================
          SMART GRADE REPORT
========================================

【學生基本資料】
審核時間：$current_time
學生學號：$id
學生科系：$dept
程式檔名：$filename

【成績審核結果】
數學成績：$score_num
成績等級：$grade
評語：$comment

【成績統計分析】
成績百分比：$percentage
及格狀態：$pass_status
等級進度：$progress

========================================
"
# 使用多行字串整理學生的完整資料
# 變數會自動替換成實際的內容


# ============================================================
# 12. 新增功能三：儲存前二次確認
# ============================================================

echo "$result_str"
# 先在畫面上顯示完整報告
# 讓使用者確認學號、成績及其他資料

read -r -p "以上資料是否正確？確定要儲存嗎？(Y/N): " confirm
# 讀取使用者的確認結果

case "$confirm" in

    Y|y|YES|yes|Yes)
        # 接受 Y、y、YES、yes、Yes

        echo "確認成功，準備儲存資料！"
        ;;

    *)
        # 其他任何輸入都取消儲存

        echo "已取消儲存，本次資料不會寫入檔案。"
        exit 0
        ;;

esac


# ============================================================
# 13. 同時顯示及寫入成績報告
# ============================================================

if echo "$result_str" | tee -a "$out_file"; then

    # echo：輸出完整報告
    # |：管線，將結果傳遞給 tee
    # tee：同時顯示及寫入檔案
    # -a：附加模式，不覆蓋原有資料

    echo ""
    echo "========================================"
    echo "審核完成！"
    echo "學生資料已成功儲存至：$out_file"
    echo "========================================"

else

    # 如果寫入失敗，就顯示錯誤訊息

    echo "錯誤：成績資料寫入失敗！"
    exit 1

fi
