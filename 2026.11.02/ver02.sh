# ============================================================
# 第一部分：讀取學生資料
# ============================================================

read -r -p "請輸入學生學號: " id
# read：讀取使用者輸入
# -r：避免反斜線被當成特殊跳脫字元
# -p：在讀取前顯示提示文字
# id：將輸入的學號儲存到變數 id

if [ -z "$id" ]; then
    # -z：檢查字串是否為空字串
    # 如果學號沒有輸入任何內容，就會成立

    echo "錯誤：學號不得為空字串！"
    # 顯示錯誤訊息

    exit 1
    # exit 1：結束程式，並回傳錯誤狀態碼
fi

read -r -p "請輸入數學成績: " score
# 讀取數學成績，儲存在 score 變數

read -r -p "請輸入程式檔案名稱: " filename
# 讀取學生繳交的程式檔名，儲存在 filename


# ============================================================
# 第二部分：使用 CASE 判斷學生科系
# ============================================================

first_char="${id:0:1}"
# ${id:0:1}：Bash 字串切割語法
# 從 id 變數的第 0 個位置開始，取出 1 個字元
# 也就是取得學號的第一個字母

case "$first_char" in
    # case：依照變數內容進行多重條件判斷

    E)
        dept="ELECTRICAL ENGINEERING"
        # 學號 E 開頭，代表電機工程系
        ;;

    C)
        dept="COMPUTER SCIENCE"
        # 學號 C 開頭，代表資訊科學系
        ;;

    M)
        dept="MECHANICAL ENGINEERING"
        # 學號 M 開頭，代表機械工程系
        ;;

    *)
        # * 代表其他所有未符合的情況

        echo "錯誤：非法的科系代號！"
        exit 1
        # 遇到非法科系代號，立即結束程式
        ;;
esac
# esac：case 的結束標記


# ============================================================
# 第三部分：檢查成績是否合法
# ============================================================

case "$score" in
    # 先檢查輸入是否為純數字

    ''|*[!0-9]*|????*)
        # ''：空字串
        # *[!0-9]*：包含非 0~9 數字的字串
        # ????*：至少有 4 個字元
        # 本題成績最高只有 100，因此最多允許輸入 3 位數

        echo "錯誤：成績必須輸入 0~100 的整數！"
        exit 1
        ;;

esac

score_num=$((10#$score))
# 將成績轉換成十進位整數
# 10# 可以避免前面有 0 時被誤認為八進位
# 例如 090 會被轉換成十進位 90

if [ "$score_num" -lt 0 ] || [ "$score_num" -gt 100 ]; then
    # -lt：小於
    # -gt：大於
    # ||：OR，只要其中一個條件成立就執行

    echo "錯誤：成績必須介於 0 到 100 之間！"
    exit 1
fi


# ============================================================
# 第四部分：使用 CASE 判斷成績等級及評語
# ============================================================

case "$score_num" in

    100|9[0-9])
        # 100 或 90~99 分
        grade="A+"
        comment="EXCELLENT"
        ;;

    8[0-9])
        # 80~89 分
        grade="A"
        comment="VERY GOOD"
        ;;

    7[0-9])
        # 70~79 分
        grade="B"
        comment="GOOD"
        ;;

    6[0-9])
        # 60~69 分
        grade="C"
        comment="PASS"
        ;;

    *)
        # 其他情況就是 0~59 分
        grade="F"
        comment="FAIL"
        ;;

esac


# ============================================================
# 第五部分：檢查學生繳交的程式檔名
# ============================================================

expected_name="${id}.SH"
# 將學號與 .SH 組合
# 例如 E1234567 會變成 E1234567.SH

if [ "$filename" != "$expected_name" ]; then
    # !=：字串不相等
    # 檢查輸入的檔名是否與規定完全相同

    echo "錯誤：檔名必須為 ${expected_name}！"
    exit 1
fi


# ============================================================
# 第六部分：依序檢查程式檔案的四種屬性
# ============================================================

if [ ! -e "$filename" ]; then
    # -e：檢查檔案或路徑是否存在
    # !：反向判斷，因此 ! -e 代表不存在

    echo "錯誤：檔案不存在！"
    exit 1

elif [ ! -f "$filename" ]; then
    # -f：檢查是否為普通檔案
    # 例如目錄就不是普通檔案

    echo "錯誤：這不是普通檔案！"
    exit 1

elif [ ! -r "$filename" ]; then
    # -r：檢查目前使用者是否具有讀取權限

    echo "錯誤：檔案不可讀取！"
    exit 1

elif [ ! -x "$filename" ]; then
    # -x：檢查目前使用者是否具有執行權限

    echo "錯誤：檔案不可執行！"
    exit 1

fi
# 只有四項條件全部通過，才會繼續執行


# ============================================================
# 第七部分：額外加分功能－計算距離下一個等級的分數
# ============================================================

case "$grade" in

    F)
        next_grade="C"
        next_score=60
        ;;

    C)
        next_grade="B"
        next_score=70
        ;;

    B)
        next_grade="A"
        next_score=80
        ;;

    A)
        next_grade="A+"
        next_score=90
        ;;

    A+)
        next_grade="最高等級"
        ;;

esac

if [ "$grade" != "A+" ]; then
    # 最高等級已經沒有下一個等級，因此不需要計算

    points_needed=$((next_score - score_num))
    # 計算距離下一個等級所需的分數
else
    points_needed=0
fi


# ============================================================
# 第八部分：檢查及決定輸出檔案
# ============================================================

out_file="GRADE"
# 預設輸出檔名為 GRADE

if [ -e "$out_file" ]; then
    # -e：如果 GRADE 已經存在，就需要另外輸入檔名

    read -r -p "GRADE 已存在，請輸入新的輸出檔名: " out_file

    if [ -z "$out_file" ] || [ "$out_file" = "GRADE" ] || [ -d "$out_file" ] || [ "$out_file" = "$filename" ]; then
        # -z：新檔名不可為空
        # = GRADE：不可再次使用 GRADE
        # -d：不可為已存在的目錄
        # = filename：不可使用學生繳交的程式檔案作為輸出檔

        echo "錯誤：新的輸出檔名不合法！"
        exit 1
    fi

fi
# 本題不使用 LOOP，因此只允許重新輸入一次


# ============================================================
# 第九部分：額外加分功能－取得系統時間
# ============================================================

current_time=$(date "+%Y-%m-%d %H:%M:%S")
# date：取得目前系統日期與時間
# $()：命令替換，將指令執行結果存入變數
# 例如 2026-11-02 14:30:00


# ============================================================
# 第十部分：整理學生完整成績報告
# ============================================================

if [ "$grade" = "A+" ]; then
    # 如果已經是最高等級，就顯示特殊訊息

    progress="已達最高等級！"

else
    progress="距離下一級 ${next_grade} 還差 ${points_needed} 分"
    # 顯示下一個等級及還需要幾分
fi


result_str="
========================================
          SMART GRADE REPORT
========================================
審核時間：$current_time
學生學號：$id
學生科系：$dept
數學成績：$score_num
成績等級：$grade
評語：$comment
等級進度：$progress
程式檔名：$filename
========================================
"
# 使用多行字串整理完整報告
# 所有變數都會在輸出時替換成實際內容


# ============================================================
# 第十一部分：同時顯示及寫入輸出檔案
# ============================================================

echo "$result_str" | tee -a "$out_file"
# echo：輸出完整報告
# |：管線，將 echo 的結果傳給 tee
# tee：同時顯示畫面並寫入檔案
# -a：Append，使用附加模式，不覆蓋原有內容


echo "處理完成！"
# 顯示完成訊息

echo "學生資料已儲存至：$out_file"
# 顯示實際使用的輸出檔名
